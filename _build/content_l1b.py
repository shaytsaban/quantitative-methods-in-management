def _tiles():
    p, X0 = [], 20
    def row(y, n, w, col, neg, x0, lab=None):
        g = ''
        for i in range(n):
            x = x0 + i * (w + 6)
            g += f'<rect x="{x}" y="{y}" width="{w}" height="30" rx="6" fill="{"#fff" if neg else col}" stroke="{"#e0454f" if neg else col}" stroke-width="3"{" stroke-dasharray=" + chr(34) + "5 4" + chr(34) if neg else ""}/>'
            g += _t(x + w / 2, y + 22, ('-' if neg else '') + (lab or ''), 17, '#e0454f' if neg else '#fff', 700)
        return g
    wx, wu = 52, 30
    p.append(_g(1, row(38, 6, wx, '#0f9d90', False, X0, 'x')))
    p.append(_g(3, row(76, 2, wx, '#0f9d90', True, X0, 'x')))
    p.append(_g(5, row(76, 1, wx, '#0f9d90', True, X0 + 2 * (wx + 6), 'x')))
    p.append(_g(2, row(160, 3, wu, '#e8960c', False, X0, '1')))
    p.append(_g(4, row(198, 5, wu, '#e8960c', True, X0, '1')))
    # every negative tile cancels one positive tile
    g = ''.join(f'<line x1="{X0 + i * (wx + 6) + 6}" y1="104" x2="{X0 + i * (wx + 6) + wx - 6}" y2="40" stroke="#16213a" stroke-width="3.5" stroke-linecap="round"/>' for i in range(3))
    p.append(_g(6, g + _t(430, 78, '= 3x', 34, '#087469'), 'fade'))
    g = ''.join(f'<line x1="{X0 + i * (wu + 6) + 4}" y1="226" x2="{X0 + i * (wu + 6) + wu - 4}" y2="162" stroke="#16213a" stroke-width="3.5" stroke-linecap="round"/>' for i in range(3))
    p.append(_g(7, g + _t(430, 200, '= -2', 34, '#a86703'), 'fade'))
    return '<div class="diagw"><svg class="diag" dir="ltr" viewBox="0 0 520 240" role="img">' + ''.join(p) + '</svg></div>'


