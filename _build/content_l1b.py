def VEQ(s, cls=''):
    """A displayed identity, checked numerically."""
    chain(s); NCHK[0] += 1
    return EQ(s, cls)


def _fruit(kind, k):
    one = '<circle cx="15" cy="17" r="11" fill="#e0454f"/><path d="M15 6q2-5 7-5" stroke="#3b7a2a" stroke-width="2.5" fill="none"/>' if kind == 'a' else '<path d="M4 8q4 20 24 18q-14-2-18-20z" fill="#f0b429" stroke="#a86703" stroke-width="1.5"/>'
    return ''.join(f'<svg viewBox="0 0 30 30" width="38" height="38" dir="ltr" aria-hidden="true">{one}</svg>' for _ in range(k))


