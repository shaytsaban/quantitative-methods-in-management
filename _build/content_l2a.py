def MINI(n0, rows, expr, ans):
    """A short worked solution inside a slide: one numbered line per click, every line checked against the solution."""
    sol = _sol_of(expr, ans)
    out = ''
    for i, x in enumerate(rows):
        m, note = _line(x, ans, sol)
        out += ST(n0 + i, f'<div class="wn"><b>{i + 1}</b><span>{TX(note)}</span></div>{_EQ(m) if m else ""}', cls='wkr' + (' fin' if i == len(rows) - 1 else ''))
    return f'<div class="wk xs">{out}</div>'


