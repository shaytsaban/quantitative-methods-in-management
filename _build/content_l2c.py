def NUMPTS(pts, lo, hi, W=560, H=96):
    """A number line with labelled points: (value, colour)."""
    x0, x1, y = 30, W - 30, 50
    X = lambda v: x0 + (v - lo) / (hi - lo) * (x1 - x0)
    g = f'<line x1="{x0 - 14}" y1="{y}" x2="{x1 + 14}" y2="{y}" stroke="#1b2d55" stroke-width="2.5"/>'
    for v in range(lo, hi + 1):
        g += f'<line x1="{X(v):.1f}" y1="{y - 6}" x2="{X(v):.1f}" y2="{y + 6}" stroke="#1b2d55" stroke-width="2"/>' + _t(X(v), y + 30, str(v), 17, '#8a93aa', 600)
    for v, col in pts:
        g += f'<circle cx="{X(v):.1f}" cy="{y}" r="9" fill="{col}"/>' + _t(X(v), y - 18, str(v), 22, col, 800)
    return f'<svg class="diag nl" dir="ltr" viewBox="0 0 {W} {H}" role="img">{g}</svg>'


